inline bool saveNet(const MLP& m, const std::string& path) {
  std::ofstream f(path, std::ios::binary);
  if (!f) return false;
  f.write("MPRF", 4);
  int n = (int)m.L.size();
  f.write((char*)&n, 4);
  for (auto& d : m.L) f.write((char*)&d.in, 4), f.write((char*)&d.out, 4);
  for (auto& d : m.L) {
    f.write((char*)d.W.data(), (std::streamsize)(d.W.size() * 4));
    f.write((char*)d.b.data(), (std::streamsize)(d.b.size() * 4));
  }
  return (bool)f;
}

inline bool loadNet(MLP& m, const std::string& path) {
  std::ifstream f(path, std::ios::binary);
  char mg[4];
  int n;
  if (!f.read(mg, 4) || std::memcmp(mg, "MPRF", 4) || !f.read((char*)&n, 4)) return false;
  m.L.assign(n, Dense());
  for (auto& d : m.L) {
    f.read((char*)&d.in, 4);
    f.read((char*)&d.out, 4);
    d.W.resize((size_t)d.in * d.out);
    d.b.resize(d.out);
  }
  for (auto& d : m.L) {
    f.read((char*)d.W.data(), (std::streamsize)(d.W.size() * 4));
    f.read((char*)d.b.data(), (std::streamsize)(d.b.size() * 4));
  }
  return (bool)f;
}

inline bool exportHeader(const MLP& m, const std::string& path, const std::string& note) {
  std::string z = z85Encode(quantize(m));
  std::ofstream f(path);
  if (!f) return false;
  f << "// Generated by tools/train.cpp - " << note << "\n";
  f << "// int8 weights, Z85-encoded: " << z.size() << " characters.\n#pragma once\n";
  f << "inline const char* NN_WEIGHTS =\n";
  // Z85 uses '?': escape it so no "??x" trigraph can form under older compilers.
  for (size_t i = 0; i < z.size(); i += 120) {
    std::string line;
    for (char c : z.substr(i, 120)) line += c == '?' ? std::string("\\?") : std::string(1, c);
    f << "    \"" << line << "\"\n";
  }
  if (z.empty()) f << "    \"\"\n";
  f << "    ;\n";
  return (bool)f;
}

// ---------------------------------------------------------------------------
// Batched training: forward with saved activations, backward, Adam
// ---------------------------------------------------------------------------
// Per-thread forward/backward with its own activations and gradient sums.
struct Worker {
  std::vector<std::vector<float>> gW, gb, act, pre;

  void setup(const MLP& net) {
    gW.resize(net.L.size());
    gb.resize(net.L.size());
    for (size_t k = 0; k < net.L.size(); ++k) {
      gW[k].assign(net.L[k].W.size(), 0.f);
      gb[k].assign(net.L[k].b.size(), 0.f);
    }
  }

  // X: B x in. Returns B x out, keeping activations for backward().
  const float* forward(const MLP& net, const float* X, int B) {
    size_t n = net.L.size();
    act.resize(n + 1);
    pre.resize(n);
    act[0].assign(X, X + (size_t)B * net.inputs());
    for (size_t k = 0; k < n; ++k) {
      const Dense& d = net.L[k];
      bool last = k + 1 == n;
      pre[k].resize((size_t)B * d.out);
      act[k + 1].resize((size_t)B * d.out);
      for (int b = 0; b < B; ++b) {
        const float* x = &act[k][(size_t)b * d.in];
        for (int o = 0; o < d.out; ++o) {
          const float* w = &d.W[(size_t)o * d.in];
          float acc = 0;
#pragma omp simd reduction(+ : acc)
          for (int i = 0; i < d.in; ++i) acc += w[i] * x[i];
          acc += d.b[o];
          pre[k][(size_t)b * d.out + o] = acc;
          act[k + 1][(size_t)b * d.out + o] = last ? acc : leaky(acc);
        }
      }
    }
    return act[n].data();
  }

  // Adds the gradient of the loss to gW/gb; dOut is dLoss/dOutput of the last forward().
  void backward(const MLP& net, std::vector<float> dOut, int B) {
    for (int k = (int)net.L.size() - 1; k >= 0; --k) {
      const Dense& d = net.L[k];
      bool last = k + 1 == (int)net.L.size();
      if (!last)
        for (size_t i = 0; i < dOut.size(); ++i)
          if (pre[k][i] <= 0) dOut[i] *= 0.01f;
      std::vector<float> dIn(k > 0 ? (size_t)B * d.in : 0, 0.f);
      for (int b = 0; b < B; ++b) {
        const float* x = &act[k][(size_t)b * d.in];
        for (int o = 0; o < d.out; ++o) {
          float g = dOut[(size_t)b * d.out + o];
          if (g == 0) continue;
          gb[k][o] += g;
          float* gw = &gW[k][(size_t)o * d.in];
#pragma omp simd
          for (int i = 0; i < d.in; ++i) gw[i] += g * x[i];
          if (k > 0) {
            const float* w = &d.W[(size_t)o * d.in];
            float* di = &dIn[(size_t)b * d.in];
#pragma omp simd
            for (int i = 0; i < d.in; ++i) di[i] += g * w[i];
          }
        }
      }
      dOut.swap(dIn);
    }
  }
};

struct Trainer {
  MLP net;
  std::vector<Worker> workers;
  std::vector<std::vector<float>> mW, vW, mb, vb;
  long t = 0;

  void setup(int threads) {
    workers.assign(std::max(1, threads), Worker());
    for (auto& w : workers) w.setup(net);
    size_t n = net.L.size();
    mW.resize(n), vW.resize(n), mb.resize(n), vb.resize(n);
    for (size_t k = 0; k < n; ++k) {
      mW[k].assign(net.L[k].W.size(), 0.f);
      vW[k] = mW[k];
      mb[k].assign(net.L[k].b.size(), 0.f);
      vb[k] = mb[k];
    }
  }

  // Sums the workers' gradients, takes one clipped Adam step, clears the sums.
  void adam(float lr, float clip = 10.f) {
    std::vector<std::vector<float>>& gW = workers[0].gW;
    std::vector<std::vector<float>>& gb = workers[0].gb;
    for (size_t w = 1; w < workers.size(); ++w)
      for (size_t k = 0; k < net.L.size(); ++k) {
        for (size_t i = 0; i < gW[k].size(); ++i) gW[k][i] += workers[w].gW[k][i], workers[w].gW[k][i] = 0;
        for (size_t i = 0; i < gb[k].size(); ++i) gb[k][i] += workers[w].gb[k][i], workers[w].gb[k][i] = 0;
      }
    double norm = 0;
    for (size_t k = 0; k < net.L.size(); ++k) {
      for (float g : gW[k]) norm += (double)g * g;
      for (float g : gb[k]) norm += (double)g * g;
    }
    norm = std::sqrt(norm);
    float scale = norm > clip ? (float)(clip / norm) : 1.f;
    ++t;
    const float b1 = 0.9f, b2 = 0.999f, eps = 1e-8f;
    float c1 = 1 - std::pow(b1, (float)t), c2 = 1 - std::pow(b2, (float)t);
    auto upd = [&](std::vector<float>& w, std::vector<float>& g, std::vector<float>& m, std::vector<float>& v) {
      for (size_t i = 0; i < w.size(); ++i) {
        float gi = g[i] * scale;
        m[i] = b1 * m[i] + (1 - b1) * gi;
        v[i] = b2 * v[i] + (1 - b2) * gi * gi;
        w[i] -= lr * (m[i] / c1) / (std::sqrt(v[i] / c2) + eps);
        g[i] = 0;
      }
    };
    for (size_t k = 0; k < net.L.size(); ++k) {
      upd(net.L[k].W, gW[k], mW[k], vW[k]);
      upd(net.L[k].b, gb[k], mb[k], vb[k]);
    }
  }
};

// Runs fn(t, lo, hi) over [0, n) split into `threads` chunks.
template <class F>
inline void parallelFor(int threads, int n, F fn) {
  threads = std::max(1, std::min(threads, n));
  if (threads == 1) return fn(0, 0, n);
  std::vector<std::thread> th;
  for (int t = 0; t < threads; ++t) th.emplace_back(fn, t, n * t / threads, n * (t + 1) / threads);
  for (auto& x : th) x.join();
}

// Batched inference without saved activations.
inline void forwardMany(const MLP& m, const float* X, int B, float* Y) {
  for (int b = 0; b < B; ++b) m.forward(X + (size_t)b * m.inputs(), Y + (size_t)b * m.outputs());
}


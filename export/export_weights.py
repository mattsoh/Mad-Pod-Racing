def _chunk_join(values, chunk=200):
    lines = []
    for i in range(0, len(values), chunk):
        lines.append(",".join(values[i : i + chunk]))
    return ",\n".join(lines)


def cpp_array_1d_float(name, arr):
    rows = arr.shape[0]
    values = [f"{v:.6g}f" for v in arr]
    body = _chunk_join(values)
    return f"static const float {name}[{rows}]={{{body}}};"


def cpp_b64_bytes(name, data_bytes):
    encoded = base64.b64encode(data_bytes).decode("ascii")
    lines = [f"static const char {name}[] ="]
    for i in range(0, len(encoded), 120):
        lines.append(f"    \"{encoded[i:i + 120]}\"")
    lines.append(";")
    return "\n".join(lines)


def quantize_int8(w):
    max_abs = float(np.max(np.abs(w)))
    if max_abs < 1e-8:
        scale = 1.0
    else:
        scale = max_abs / 127.0
    q = np.round(w / scale).clip(-127, 127).astype(np.int8)
    return q, float(scale)


def build_cpp(w1, b1, w2, b2, w3, b3, out_path, quantize=True):
    h1 = w1.shape[0]
    h2 = w2.shape[0]
    code = []
    code.append("#include <bits/stdc++.h>")
    code.append("using namespace std;")
    code.append("")
    code.append(f"static const int OBS_SIZE = {OBS_SIZE};")
    code.append(f"static const int ACTION_SIZE = {ACTION_SIZE};")
    code.append(f"static const int H1 = {h1};")
    code.append(f"static const int H2 = {h2};")
    code.append("")
    if quantize:
        q1, s1 = quantize_int8(w1)
        q2, s2 = quantize_int8(w2)
        q3, s3 = quantize_int8(w3)
        code.append(cpp_b64_bytes("FC1_W_B64", q1.reshape(-1).tobytes()))
        code.append(cpp_array_1d_float("FC1_B", b1))
        code.append(f"static const float FC1_S={s1:.6g}f;")
        code.append(cpp_b64_bytes("FC2_W_B64", q2.reshape(-1).tobytes()))
        code.append(cpp_array_1d_float("FC2_B", b2))
        code.append(f"static const float FC2_S={s2:.6g}f;")
        code.append(cpp_b64_bytes("OUT_W_B64", q3.reshape(-1).tobytes()))
        code.append(cpp_array_1d_float("OUT_B", b3))
        code.append(f"static const float OUT_S={s3:.6g}f;")
    else:
        code.append(cpp_array_1d_float("FC1_W", w1.reshape(-1)))
        code.append(cpp_array_1d_float("FC1_B", b1))
        code.append(cpp_array_1d_float("FC2_W", w2.reshape(-1)))
        code.append(cpp_array_1d_float("FC2_B", b2))
        code.append(cpp_array_1d_float("OUT_W", w3.reshape(-1)))
        code.append(cpp_array_1d_float("OUT_B", b3))
    code.append("")
    code.append("struct Vec { float x; float y; };")
    code.append("static const float MAP_W = 16000.0f;")
    code.append("static const float MAP_H = 9000.0f;")
    code.append("")
    if quantize:
        code.append("static int b64_index(char c) {")
        code.append("    if (c >= 'A' && c <= 'Z') return c - 'A';")
        code.append("    if (c >= 'a' && c <= 'z') return c - 'a' + 26;")
        code.append("    if (c >= '0' && c <= '9') return c - '0' + 52;")
        code.append("    if (c == '+') return 62;")
        code.append("    if (c == '/') return 63;")
        code.append("    return -1;")
        code.append("}")
        code.append("")
        code.append("static vector<uint8_t> decode_base64(const char* s) {")
        code.append("    vector<uint8_t> out;")
        code.append("    int val = 0;")
        code.append("    int valb = -8;")
        code.append("    for (const char* p = s; *p; ++p) {")
        code.append("        int idx = b64_index(*p);")
        code.append("        if (idx < 0) continue;")
        code.append("        val = (val << 6) + idx;")
        code.append("        valb += 6;")
        code.append("        if (valb >= 0) {")
        code.append("            out.push_back((uint8_t)((val >> valb) & 0xFF));")
        code.append("            valb -= 8;")
        code.append("        }")
        code.append("    }")
        code.append("    return out;")
        code.append("}")
        code.append("")
        code.append("static vector<int8_t> decode_base64_i8(const char* s) {")
        code.append("    vector<uint8_t> bytes = decode_base64(s);")
        code.append("    vector<int8_t> out(bytes.size());")
        code.append("    for (size_t i = 0; i < bytes.size(); ++i) out[i] = (int8_t)bytes[i];")
        code.append("    return out;")
        code.append("}")
        code.append("")
        code.append("static void dense_tanh_q(const int8_t* w, const float* b, float scale, const float* x, float* out, int rows, int cols) {")
        code.append("    for (int r = 0; r < rows; ++r) {")
        code.append("        float sum = b[r];")
        code.append("        const int8_t* wr = w + r * cols;")
        code.append("        float acc = 0.0f;")
        code.append("        for (int c = 0; c < cols; ++c) {")
        code.append("            acc += (float)wr[c] * x[c];")
        code.append("        }")
        code.append("        sum += acc * scale;")
        code.append("        out[r] = tanh(sum);")
        code.append("    }")
        code.append("}")
        code.append("")
        code.append("static void dense_linear_q(const int8_t* w, const float* b, float scale, const float* x, float* out, int rows, int cols) {")
        code.append("    for (int r = 0; r < rows; ++r) {")
        code.append("        float sum = b[r];")
        code.append("        const int8_t* wr = w + r * cols;")
        code.append("        float acc = 0.0f;")
        code.append("        for (int c = 0; c < cols; ++c) {")
        code.append("            acc += (float)wr[c] * x[c];")
        code.append("        }")
        code.append("        out[r] = sum + acc * scale;")
        code.append("    }")
        code.append("}")
    else:
        code.append("static void dense_tanh(const float* w, const float* b, const float* x, float* out, int rows, int cols) {")
        code.append("    for (int r = 0; r < rows; ++r) {")
        code.append("        float sum = b[r];")
        code.append("        const float* wr = w + r * cols;")
        code.append("        for (int c = 0; c < cols; ++c) {")
        code.append("            sum += wr[c] * x[c];")
        code.append("        }")
        code.append("        out[r] = tanh(sum);")
        code.append("    }")
        code.append("}")
        code.append("")
        code.append("static void dense_linear(const float* w, const float* b, const float* x, float* out, int rows, int cols) {")
        code.append("    for (int r = 0; r < rows; ++r) {")
        code.append("        float sum = b[r];")
        code.append("        const float* wr = w + r * cols;")
        code.append("        for (int c = 0; c < cols; ++c) {")
        code.append("            sum += wr[c] * x[c];")
        code.append("        }")
        code.append("        out[r] = sum;")
        code.append("    }")
        code.append("}")
    code.append("")
    code.append("static void build_obs(vector<float>& obs, const vector<Vec>& checkpoints, int laps, int checkpointCount, const array<int,4>& x, const array<int,4>& y, const array<int,4>& vx, const array<int,4>& vy, const array<int,4>& ang, const array<int,4>& nextId, const array<int,4>& lap, const array<int,2>& shieldCd, bool boostAvailable) {")
    code.append("    obs.clear();")
    code.append("    obs.reserve(OBS_SIZE);")
    code.append("    for (int i = 0; i < 4; ++i) {")
    code.append("        float px = (x[i] - MAP_W * 0.5f) / (MAP_W * 0.5f);")
    code.append("        float py = (y[i] - MAP_H * 0.5f) / (MAP_H * 0.5f);")
    code.append("        float vxn = vx[i] / 1000.0f;")
    code.append("        float vyn = vy[i] / 1000.0f;")
    code.append("        float rad = ang[i] * 3.14159265f / 180.0f;")
    code.append("        float c = cos(rad);")
    code.append("        float s = sin(rad);")
    code.append("        Vec cp = checkpoints[nextId[i]];")
    code.append("        float relx = (cp.x - x[i]) / MAP_W;")
    code.append("        float rely = (cp.y - y[i]) / MAP_H;")
    code.append("        float dx = cp.x - x[i];")
    code.append("        float dy = cp.y - y[i];")
    code.append("        float dist = sqrt(dx * dx + dy * dy) / 20000.0f;")
    code.append("        if (dist > 1.0f) dist = 1.0f;")
    code.append("        float lapFrac = laps > 0 ? (float)lap[i] / (float)laps : 0.0f;")
    code.append("        float nextFrac = checkpointCount > 1 ? (float)nextId[i] / (float)(checkpointCount - 1) : 0.0f;")
    code.append("        float shield = 0.0f;")
    code.append("        if (i < 2) shield = shieldCd[i] / 3.0f;")
    code.append("        obs.push_back(px);")
    code.append("        obs.push_back(py);")
    code.append("        obs.push_back(vxn);")
    code.append("        obs.push_back(vyn);")
    code.append("        obs.push_back(c);")
    code.append("        obs.push_back(s);")
    code.append("        obs.push_back(relx);")
    code.append("        obs.push_back(rely);")
    code.append("        obs.push_back(dist);")
    code.append("        obs.push_back(lapFrac);")
    code.append("        obs.push_back(nextFrac);")
    code.append("        obs.push_back(shield);")
    code.append("    }")
    code.append("    obs.push_back(boostAvailable ? 1.0f : 0.0f);")
    code.append("}")
    code.append("")
    code.append("int main() {")
    code.append("    ios::sync_with_stdio(false);")
    code.append("    cin.tie(nullptr);")
    code.append("")
    code.append("    int laps; int checkpointCount;")
    code.append("    if (!(cin >> laps)) return 0;")
    code.append("    cin >> checkpointCount;")
    code.append("    vector<Vec> checkpoints(checkpointCount);")
    code.append("    for (int i = 0; i < checkpointCount; ++i) {")
    code.append("        cin >> checkpoints[i].x >> checkpoints[i].y;")
    code.append("    }")
    code.append("")
    code.append("    array<int,4> prevNext; prevNext.fill(-1);")
    code.append("    array<int,4> lap; lap.fill(0);")
    code.append("    array<int,2> shieldCd; shieldCd.fill(0);")
    code.append("    bool boostAvailable = true;")
    code.append("")
    if quantize:
        code.append("    vector<int8_t> fc1_w = decode_base64_i8(FC1_W_B64);")
        code.append("    vector<int8_t> fc2_w = decode_base64_i8(FC2_W_B64);")
        code.append("    vector<int8_t> out_w = decode_base64_i8(OUT_W_B64);")
        code.append("")
    code.append("    while (true) {")
    code.append("        array<int,4> x, y, vx, vy, ang, nextId;")
    code.append("        for (int i = 0; i < 4; ++i) {")
    code.append("            if (!(cin >> x[i] >> y[i] >> vx[i] >> vy[i] >> ang[i] >> nextId[i])) {")
    code.append("                return 0;")
    code.append("            }")
    code.append("            if (prevNext[i] == checkpointCount - 1 && nextId[i] == 0) {")
    code.append("                lap[i] += 1;")
    code.append("            }")
    code.append("            prevNext[i] = nextId[i];")
    code.append("        }")
    code.append("")
    code.append("        for (int i = 0; i < 2; ++i) {")
    code.append("            if (shieldCd[i] > 0) shieldCd[i] -= 1;")
    code.append("        }")
    code.append("")
    code.append("        vector<float> obs;")
    code.append("        build_obs(obs, checkpoints, laps, checkpointCount, x, y, vx, vy, ang, nextId, lap, shieldCd, boostAvailable);")
    code.append("")
    code.append("        float h1[H1];")
    code.append("        float h2[H2];")
    code.append("        float out[ACTION_SIZE];")
    if quantize:
        code.append("        dense_tanh_q(fc1_w.data(), FC1_B, FC1_S, obs.data(), h1, H1, OBS_SIZE);")
        code.append("        dense_tanh_q(fc2_w.data(), FC2_B, FC2_S, h1, h2, H2, H1);")
        code.append("        dense_linear_q(out_w.data(), OUT_B, OUT_S, h2, out, ACTION_SIZE, H2);")
    else:
        code.append("        dense_tanh(FC1_W, FC1_B, obs.data(), h1, H1, OBS_SIZE);")
        code.append("        dense_tanh(FC2_W, FC2_B, h1, h2, H2, H1);")
        code.append("        dense_linear(OUT_W, OUT_B, h2, out, ACTION_SIZE, H2);")
    code.append("")
    code.append("        for (int i = 0; i < ACTION_SIZE; ++i) {")
    code.append("            out[i] = tanh(out[i]);")
    code.append("        }")
    code.append("")
    code.append("        for (int pod = 0; pod < 2; ++pod) {")
    code.append("            float ax = out[pod * 4 + 0];")
    code.append("            float ay = out[pod * 4 + 1];")
    code.append("            float thrustRaw = out[pod * 4 + 2];")
    code.append("            float special = out[pod * 4 + 3];")
    code.append("            int tx = (int)((ax + 1.0f) * 0.5f * MAP_W);")
    code.append("            int ty = (int)((ay + 1.0f) * 0.5f * MAP_H);")
    code.append("            int thrust = (int)((thrustRaw + 1.0f) * 50.0f);")
    code.append("            if (thrust < 0) thrust = 0;")
    code.append("            if (thrust > 100) thrust = 100;")
    code.append("            if (special > 0.5f && boostAvailable) {")
    code.append("                cout << tx << \" \" << ty << \" BOOST\" << '\\n';")
    code.append("                boostAvailable = false;")
    code.append("            } else if (special < -0.5f) {")
    code.append("                cout << tx << \" \" << ty << \" SHIELD\" << '\\n';")
    code.append("                shieldCd[pod] = 3;")
    code.append("            } else {")
    code.append("                cout << tx << \" \" << ty << \" \" << thrust << '\\n';")
    code.append("            }")
    code.append("        }")
    code.append("        cout.flush();")
    code.append("    }")
    code.append("    return 0;")
    code.append("}")

    with open(out_path, "w", encoding="utf-8") as f:
        f.write("\n".join(code))


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--checkpoint", required=True)
    parser.add_argument("--out", default="export/trained_bot.cpp")
    parser.add_argument("--no-quantize", action="store_true")
    parser.add_argument("--hidden-size", type=int, default=0)
    args = parser.parse_args()

    state = torch.load(args.checkpoint, map_location="cpu")
    inferred = int(state["fc1.weight"].shape[0]) if "fc1.weight" in state else 128
    hidden_size = args.hidden_size if args.hidden_size > 0 else inferred

    policy = PolicyNet(OBS_SIZE, ACTION_SIZE, hidden_size)
    policy.load_state_dict(state)

    w1 = policy.fc1.weight.detach().cpu().numpy()
    b1 = policy.fc1.bias.detach().cpu().numpy()
    w2 = policy.fc2.weight.detach().cpu().numpy()
    b2 = policy.fc2.bias.detach().cpu().numpy()
    w3 = policy.action_head.weight.detach().cpu().numpy()
    b3 = policy.action_head.bias.detach().cpu().numpy()

    build_cpp(w1, b1, w2, b2, w3, b3, args.out, quantize=not args.no_quantize)


if __name__ == "__main__":
    main()

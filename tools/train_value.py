"""Trains the value network (tools/value_data.cpp's dataset) and exports it in the bot's weights format.

    python3 tools/train_value.py data/value.bin nets/value16 --hidden 16 --epochs 12

Regression of the lead change over the next 30 turns (in checkpoints) from the 48 network features; games
held out 10% by id. Left-right mirrored copies are added (the target does not change). Writes PREFIX.pt and
PREFIX_weights.h (NN_VALUE, int8 + Z85 like NN_WEIGHTS).
"""
import argparse, struct
import numpy as np
import torch, torch.nn as nn

ap = argparse.ArgumentParser()
ap.add_argument("data"); ap.add_argument("out")
ap.add_argument("--hidden", type=int, default=16)
ap.add_argument("--epochs", type=int, default=12)
ap.add_argument("--lr", type=float, default=2e-3)
a = ap.parse_args()
torch.manual_seed(0); torch.set_num_threads(4)
NF = 48
raw = np.fromfile(a.data, dtype=np.uint8)
rec = 4 * (NF + 1) + 8
raw = raw[: len(raw) // rec * rec].reshape(-1, rec)
F = raw[:, : 4 * (NF + 1)].copy().view(np.float32)
meta = raw[:, 4 * (NF + 1):].copy().view(np.int32)
X, y, gid = F[:, :NF], F[:, NF], meta[:, 0]
X[:, 44:48] = np.array([0, 0, 0, 1], np.float32)  # last move masked, as at a rollout's horizon where V is used
test = (gid.astype(np.int64) * 2654435761 >> 7) % 1000 < 100
MIRROR = [2, 4, 6, 8, 15, 17, 19, 21, 24, 26, 28, 30, 33, 35, 37, 39, 44]
Xtr, ytr = X[~test], y[~test]
Xm = Xtr.copy(); Xm[:, MIRROR] *= -1
Xtr = np.concatenate([Xtr, Xm]); ytr = np.concatenate([ytr, ytr])
Xte, yte = torch.tensor(X[test]), torch.tensor(y[test])
print(f"train {len(Xtr)} (with mirrors), test {len(yte)}; target mean {y.mean():.3f} sd {y.std():.3f}")
# linear baseline
A = np.c_[X[~test], np.ones((~test).sum())]
w = np.linalg.lstsq(A, y[~test], rcond=None)[0]
lin = np.c_[X[test], np.ones(test.sum())] @ w
r2 = lambda p, t: 1 - ((p - t) ** 2).mean() / t.var()
print(f"linear R2 {r2(lin, y[test]):.4f}")
H = a.hidden
net = nn.Sequential(nn.Linear(NF, H), nn.LeakyReLU(0.01), nn.Linear(H, H), nn.LeakyReLU(0.01), nn.Linear(H, 1))
opt = torch.optim.AdamW(net.parameters(), lr=a.lr, weight_decay=1e-4)
Xt, yt = torch.tensor(Xtr), torch.tensor(ytr)
steps = a.epochs * (len(Xt) // 2048 + 1)
sched = torch.optim.lr_scheduler.OneCycleLR(opt, max_lr=a.lr, total_steps=steps)
for ep in range(a.epochs):
    perm = torch.randperm(len(Xt))
    for i in range(0, len(perm), 2048):
        b = perm[i:i + 2048]
        loss = ((net(Xt[b]).squeeze(1) - yt[b]) ** 2).mean()
        opt.zero_grad(); loss.backward(); opt.step(); sched.step()
    with torch.no_grad():
        p = net(Xte).squeeze(1)
        print(f"epoch {ep + 1}: test R2 {r2(p.numpy(), yte.numpy()):.4f}", flush=True)
torch.save(net.state_dict(), a.out + ".pt")
lin_ = [m for m in net if isinstance(m, nn.Linear)]
blob = bytearray(b"MPR1") + bytes([len(lin_)])
for L in lin_: blob += struct.pack("<HH", L.in_features, L.out_features)
for L in lin_:
    W = L.weight.detach().numpy().astype(np.float64)
    for o in range(W.shape[0]):
        mx = np.abs(W[o]).max(); sc = np.float32(mx / 127.0 if mx > 0 else 1.0)
        blob += struct.pack("<f", sc) + np.clip(np.round(W[o] / sc), -127, 127).astype(np.int8).tobytes()
    blob += L.bias.detach().numpy().astype("<f4").tobytes()
while len(blob) % 4: blob.append(0)
Z = "0123456789abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ.-:+=^!/*?&<>()[]{}@%$#"
s = []
for i in range(0, len(blob), 4):
    v = int.from_bytes(blob[i:i + 4], "big"); c = []
    for _ in range(5): c.append(Z[v % 85]); v //= 85
    s.append("".join(reversed(c)))
z = "".join(s)
with open(a.out + "_weights.h", "w") as f:
    f.write(f"// Generated by tools/train_value.py - value of a state (lead change over 30 turns), {NF}-{H}-{H}-1\n")
    f.write("#pragma once\ninline const char* NN_VALUE =\n")
    for i in range(0, len(z), 120):
        f.write('    "' + z[i:i + 120].replace("?", "\\?") + '"' + (";\n" if i + 120 >= len(z) else "\n"))
print(f"{len(z)} characters -> {a.out}_weights.h")
